from collections.abc import Iterator
from pathlib import Path

import pytest
from alembic import command
from alembic.config import Config

from hola_hello_ciao.core.config import get_settings

ROOT = Path(__file__).resolve().parents[3]


@pytest.fixture
def alembic_config(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> Iterator[Config]:
    """Alembic pointed at a fresh temp database (migrations/env.py reads Settings)."""
    monkeypatch.setenv("DATABASE_PATH", str(tmp_path / "migrated.db"))
    get_settings.cache_clear()
    config = Config(ROOT / "alembic.ini")
    config.set_main_option("script_location", str(ROOT / "migrations"))
    yield config
    get_settings.cache_clear()


def test_migrations_match_the_models(alembic_config: Config) -> None:
    # The other tests build the schema with create_all, so only this catches model drift.
    command.upgrade(alembic_config, "head")

    command.check(alembic_config)  # raises AutogenerateDiffsDetected on drift


def test_migrations_downgrade_cleanly(alembic_config: Config) -> None:
    command.upgrade(alembic_config, "head")

    command.downgrade(alembic_config, "base")
